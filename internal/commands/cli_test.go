func TestAnalyzePackagesErrors(t *testing.T) {
	tests := []struct {
		name        string
		extra       map[string]string
		errContains []string
	}{
		{
			"bad sql names the file",
			map[string]string{"internal/accounts/bad.sql": "-- name: Oops :one\nSELECT FROM;"},
			[]string{"internal/accounts/bad.sql"},
		},
		{
			"unknown table names the file",
			map[string]string{"internal/accounts/bad.sql": "-- name: Oops :many\nSELECT id FROM nope;"},
			[]string{"internal/accounts/bad.sql"},
		},
		{
			// two Go functions with the same name in one package won't compile
			"duplicate name across files in one package",
			map[string]string{"internal/accounts/dupe.sql": "-- name: GetUser :one\nSELECT id FROM users WHERE id = $1;"},
			[]string{"GetUser"},
		},
		{
			"every failing file is reported, not just the first",
			map[string]string{
				"internal/accounts/a_bad.sql": "-- name: A :one\nSELECT FROM;",
				"internal/billing/b_bad.sql":  "-- name: B :many\nSELECT id FROM nope;",
			},
			[]string{"a_bad.sql", "b_bad.sql"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			files := basicProject()
			for k, v := range tt.extra {
				files[k] = v
			}
			_, err := analyze(t, files)
			if err == nil {
				t.Fatal("expected an error, got none")
			}
			for _, want := range tt.errContains {
				if !strings.Contains(err.Error(), want) {
					t.Errorf("error %q should mention %q", err, want)
				}
			}
		})
	}
}

/* ---------- render ---------- */

func renderProject(t *testing.T, files map[string]string) []OutputFile {
	t.Helper()
	fsys := mapFS(files)
	proj := mustDiscover(t, fsys)
	c, err := loadCatalog(fsys, proj)
	if err != nil {
		t.Fatalf("catalog: %v", err)
	}
	pkgs, err := analyzePackages(fsys, proj, c)
	if err != nil {
		t.Fatalf("analyze: %v", err)
	}
	outputs, err := render(proj, c, pkgs)
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	return outputs
}

func TestRenderPaths(t *testing.T) {
	got := outputPaths(renderProject(t, basicProject()))
	want := []string{
		"internal/accounts/queries.sql.go",
		"internal/models/db.go",
		"internal/models/models.go",
	}
	if !slices.Equal(got, want) {
		t.Errorf("output paths:\n got: %v\nwant: %v", got, want)
	}
}

