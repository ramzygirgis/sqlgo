// analyze runs discovery, the catalog and analysis over an in-memory project.
// Because it's in-memory, a pass also proves analyzePackages reads through
// fsys and not the real disk.
func analyze(t *testing.T, files map[string]string) ([]AnalyzedPackage, error) {
	t.Helper()
	fsys := mapFS(files)
	proj := mustDiscover(t, fsys)
	c, err := loadCatalog(fsys, proj)
	if err != nil {
		t.Fatalf("catalog: %v", err)
	}
	return analyzePackages(fsys, proj, c)
}

func TestAnalyzePackages(t *testing.T) {
	pkgs, err := analyze(t, basicProject())
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if len(pkgs) != 1 {
		t.Fatalf("got %d packages, want 1: %+v", len(pkgs), pkgs)
	}
	p := pkgs[0]
	if p.Dir != "internal/accounts" || p.ImportPath != "github.com/you/app/internal/accounts" {
		t.Errorf("package info = %+v", p.DirectoryInfo)
	}
	if len(p.Files) != 1 {
		t.Fatalf("got %d files, want 1", len(p.Files))
	}
	f := p.Files[0]
	if f.SourcePath != "internal/accounts/queries.sql" {
		t.Errorf("SourcePath = %q, want internal/accounts/queries.sql", f.SourcePath)
	}
	var names []string
	for _, q := range f.Queries {
		names = append(names, q.Name)
	}
	if want := []string{"GetUser", "ListUsers", "CreateUser"}; !slices.Equal(names, want) {
		t.Errorf("queries = %v, want %v (in file order)", names, want)
	}
}

