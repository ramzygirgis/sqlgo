// generateIn runs Generate from dir, the way a user would from a shell.
func generateIn(t *testing.T, dir string) error {
	t.Helper()
	t.Chdir(dir)
	return Generate()
}

func TestGenerate(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, basicProject())

	if err := generateIn(t, root); err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	for _, p := range []string{
		"internal/models/models.go",
		"internal/models/db.go",
		"internal/accounts/queries.sql.go",
	} {
		if !exists(t, root, p) {
			t.Errorf("%s was not generated", p)
		} else if !strings.HasPrefix(readFile(t, root, p), codegen.GetCodegenHeader()) {
			t.Errorf("%s is missing the generated header", p)
		}
	}
	if got := readFile(t, root, "internal/accounts/queries.sql.go"); !strings.Contains(got, "func GetUser(") {
		t.Errorf("queries.sql.go is missing GetUser:\n%s", got)
	}
}

