package commands

import (
	"errors"
	"fmt"
	"github.com/ramzygirgis/sqlgo/internal/codegen"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

func writeFileAtomic(fullPath string, contents string, pattern string) error {
	tmpFile, err := os.CreateTemp(filepath.Dir(fullPath), pattern)
	if err != nil {
		return err
	}

	cleanup := true
	defer func() {
		if cleanup {
			_ = tmpFile.Close()
			_ = os.Remove(tmpFile.Name())
		}
	}()

	if _, err = tmpFile.WriteString(contents); err != nil {
		return err
	}

	if err = tmpFile.Chmod(0o644); err != nil {
		return err
	}

	if err = tmpFile.Close(); err != nil {
		return err
	}

	if err = os.Rename(tmpFile.Name(), fullPath); err != nil {
		return err
	}

	cleanup = false
	return nil
}

func isSqlGoFile(fileContents string) bool {
	return strings.HasPrefix(fileContents, codegen.GetCodegenHeader())
}

func shouldWriteFile(fullPath string, outputFile OutputFile) (bool, error) {
	contentBytes, err := os.ReadFile(fullPath)
	if errors.Is(err, fs.ErrNotExist) {
		return true, nil
	}
	if err != nil {
		return false, err
	}
	contents := string(contentBytes)

	if len(contentBytes) != 0 {
		if !isSqlGoFile(contents) {
			return false, fmt.Errorf("cannot write to %s: file already exists and was not generated by sqlgo", fullPath)
		}
		if contents == string(outputFile.Contents) {
			return false, nil // already exists, i think that this is the correct way to skip here
		}
	}
	return true, nil
}

func shouldDeleteStale(stalePath string) (bool, error) {
	contentBytes, err := os.ReadFile(stalePath)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	contents := string(contentBytes)

	if !isSqlGoFile(contents) {
		return false, nil
	}

	return true, nil
}
